import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {randomUUID,createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {root} from '../src/config.mjs';
import {prepareWslDependency,preparedNpmDependency} from '../src/wslChecks.mjs';
import {wslCodexConfig,wslTrustedCommandLaunch,asynchronousProbe} from '../src/wslCodex.mjs';

if(process.platform!=='win32')throw new Error('Windows WSL2 required');
const base=path.join(root,'data'),dir=path.join(base,`wsl-deps-${randomUUID()}`);
assert.equal(fs.existsSync(dir),false);fs.mkdirSync(dir);
const git=(...args)=>execFileSync('git',args,{cwd:dir,encoding:'utf8',windowsHide:true});
const step={ifMissing:'node_modules',command:['npm','ci','--ignore-scripts','--no-audit','--no-fund']};
try{
  fs.writeFileSync(path.join(dir,'package.json'),JSON.stringify({name:'workspace-deps-fixture',version:'1.0.0',private:true}));
  fs.writeFileSync(path.join(dir,'package-lock.json'),JSON.stringify({name:'workspace-deps-fixture',version:'1.0.0',lockfileVersion:3,requires:true,packages:{'':{name:'workspace-deps-fixture',version:'1.0.0'}}}));
  git('init');git('add','package.json','package-lock.json');git('-c','user.name=Workspace Test','-c','user.email=workspace@example.invalid','commit','-m','fixture');
  const first=await prepareWslDependency(dir,step);assert.equal(first.ok,true,first.output);
  fs.mkdirSync(path.join(dir,'node_modules'),{recursive:true});
  const second=await prepareWslDependency(dir,step);assert.equal(second.ok,true);assert.doesNotMatch(second.output,/Previously prepared/,'An empty node_modules directory is not an install marker');
  const fakePackage=path.join(dir,'node_modules','fake-package');fs.mkdirSync(fakePackage);
  fs.writeFileSync(path.join(fakePackage,'package.json'),'{"name":"fake-package","version":"1.0.0"}');
  fs.writeFileSync(path.join(dir,'node_modules','.package-lock.json'),JSON.stringify({packages:{'node_modules/fake-package':{version:'1.0.0'}}}));
  assert.equal(preparedNpmDependency(dir,step),true);
  fs.rmSync(path.join(fakePackage,'package.json'));
  assert.equal(preparedNpmDependency(dir,step),false,'A missing installed package must force dependency setup again');
  fs.writeFileSync(path.join(fakePackage,'package.json'),'{"name":"fake-package","version":"1.0.0"}');
  const requiredLock=JSON.parse(fs.readFileSync(path.join(dir,'package-lock.json'),'utf8'));
  requiredLock.packages['node_modules/missing-required']={version:'1.0.0'};
  fs.writeFileSync(path.join(dir,'package-lock.json'),JSON.stringify(requiredLock));
  const marker=path.join(root,'data','check-deps',`${createHash('sha256').update(path.resolve(dir)+'|node_modules').digest('hex')}.json`);
  const digest=createHash('sha256').update(fs.readFileSync(path.join(dir,'package-lock.json'))).update(fs.readFileSync(path.join(dir,'package.json'))).update(JSON.stringify(step.command)).digest('hex');
  fs.writeFileSync(marker,JSON.stringify({digest}));
  assert.equal(preparedNpmDependency(dir,step),false,'A required lockfile package missing from the installed index must force setup again');
  fs.writeFileSync(path.join(dir,'package.json'),JSON.stringify({name:'workspace-deps-fixture',version:'2.0.0'}));
  await assert.rejects(prepareWslDependency(dir,step),/manifest or npm configuration changed/);
  await assert.rejects(prepareWslDependency(dir,{...step,command:[...step.command,'--ignore-scripts=false']}),/reviewed npm ci/);
  fs.writeFileSync(path.join(dir,'package.json'),JSON.stringify({name:'workspace-deps-fixture',version:'1.0.0',private:true}));
  const unsafe=JSON.parse(fs.readFileSync(path.join(dir,'package-lock.json'),'utf8'));
  unsafe.packages.bad={resolved:'https://example.invalid/evil.tgz'};
  fs.writeFileSync(path.join(dir,'package-lock.json'),JSON.stringify(unsafe));
  git('add','package-lock.json');git('-c','user.name=Workspace Test','-c','user.email=workspace@example.invalid','commit','-m','unsafe fixture');
  await assert.rejects(prepareWslDependency(dir,step),/unapproved remote registry/);
  fs.mkdirSync(path.join(dir,'design-lab'));
  const config=wslCodexConfig(dir);
  assert.equal(config.mode,'wsl-design','An existing lab must select the protected design profile before dependencies are installed');
  assert.ok(fs.statSync(path.join(dir,'design-lab','node_modules')).isDirectory());
  const nested=path.join(dir,'design-lab','node_modules','workspace-denied.txt');
  const denied=await asynchronousProbe(wslTrustedCommandLaunch(dir,['/usr/bin/env',`CODEX_HOME=${config.codexHome}`,config.binary,'sandbox','-p',config.profile,'-P',config.permission,'-C',config.worktree,'--','/bin/sh','-c','printf BAD > "$1"','probe',`${config.worktree}/design-lab/node_modules/workspace-denied.txt`]),60000);
  assert.notEqual(denied.status,0,'An empty nested dependency mount must already be read-only to the agent');
  assert.equal(fs.existsSync(nested),false);
  console.log(JSON.stringify({status:'PASS',boundedSetup:true,lockedManifest:true,markerOutsideWorktree:true}));
}finally{fs.rmSync(path.join(root,'data','check-deps',`${createHash('sha256').update(path.resolve(dir)+'|node_modules').digest('hex')}.json`),{force:true});if(path.resolve(dir).startsWith(path.resolve(base)+path.sep))fs.rmSync(dir,{recursive:true,force:true});}
